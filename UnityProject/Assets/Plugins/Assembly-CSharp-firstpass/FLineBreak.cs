	public static FLineBreakStatus[] GetBreaks(string s, string lang)
	{
		if (s == null)
		{
			return null;
		}
		int posCur = 0;
		uint ch = GetNextChar(s, ref posCur);
		if (ch == EOS)
		{
			return null;
		}
		FLineBreakProperties[] lbpLang = get_lb_prop_lang(lang);
		FLineBreakClass lbcCur = resolve_lb_class(get_char_lb_class_lang(ch, lbpLang), lang);
		FLineBreakStatus[] brks = new FLineBreakStatus[s.Length];
		FLineBreakClass lbcNew = FLineBreakClass.LBP_Undefined;
		int posLast = -1;
		bool remap = true;
		for (;;)
		{
			if (remap)
			{
				// start of a line: map CB/LF/NL/SP of the first character
				switch (lbcCur)
				{
				case FLineBreakClass.LBP_CB:
					lbcCur = FLineBreakClass.LBP_BA;
					break;
				case FLineBreakClass.LBP_LF:
				case FLineBreakClass.LBP_NL:
					lbcCur = FLineBreakClass.LBP_BK;
					break;
				case FLineBreakClass.LBP_SP:
					lbcCur = FLineBreakClass.LBP_WJ;
					break;
				}
				remap = false;
			}
			FLineBreakClass cur = lbcCur;
			FLineBreakClass lbcLast = lbcNew;
			int p = posLast;
			for (;;)
			{
				posLast = p + 1;
				if (posLast < posCur - 1)
				{
					for (int k = posLast; k < posCur - 1; k++)
					{
						brks[k] = FLineBreakStatus.InsideAChar;
					}
					posLast = posCur - 1;
				}
				ch = GetNextChar(s, ref posCur);
				if (ch == EOS)
				{
					brks[posLast] = FLineBreakStatus.MustBreak;
					for (int k = posCur; k < s.Length; k++)
					{
						brks[k] = FLineBreakStatus.InsideAChar;
					}
					return brks;
				}
				lbcNew = get_char_lb_class_lang(ch, lbpLang);
				if (cur == FLineBreakClass.LBP_BK || (cur == FLineBreakClass.LBP_CR && lbcNew != FLineBreakClass.LBP_LF))
				{
					brks[posLast] = FLineBreakStatus.MustBreak;
					lbcCur = resolve_lb_class(lbcNew, lang);
					remap = true;
					break;
				}
				p = posLast;
				if (lbcNew == FLineBreakClass.LBP_SP)
				{
					brks[posLast] = FLineBreakStatus.NoBreak;
					lbcLast = FLineBreakClass.LBP_SP;
					continue;
				}
				if (lbcNew == FLineBreakClass.LBP_BK || lbcNew == FLineBreakClass.LBP_LF || lbcNew == FLineBreakClass.LBP_NL)
				{
					brks[posLast] = FLineBreakStatus.NoBreak;
					lbcCur = FLineBreakClass.LBP_BK;
					break;
				}
				if (lbcNew == FLineBreakClass.LBP_CB)
				{
					brks[posLast] = FLineBreakStatus.AllowBreak;
					lbcCur = FLineBreakClass.LBP_BA;
					break;
				}
				if (lbcNew == FLineBreakClass.LBP_CR)
				{
					brks[posLast] = FLineBreakStatus.NoBreak;
					lbcCur = FLineBreakClass.LBP_CR;
					break;
				}
				lbcNew = resolve_lb_class(lbcNew, lang);
				BreakAction action = baTable[(int)cur - 1, (int)lbcNew - 1];
				lbcCur = lbcNew;
				if (action == BreakAction.CMP_BRK)
				{
					brks[posLast] = FLineBreakStatus.NoBreak;
					bool wasNotSpace = lbcLast != FLineBreakClass.LBP_SP;
					lbcLast = lbcNew;
					if (wasNotSpace)
					{
						continue;
					}
					break;
				}
				if (action == BreakAction.IND_BRK || action == BreakAction.CMI_BRK)
				{
					brks[posLast] = (lbcLast != FLineBreakClass.LBP_SP) ? FLineBreakStatus.NoBreak : FLineBreakStatus.AllowBreak;
				}
				else if (action == BreakAction.PRH_BRK)
				{
					brks[posLast] = FLineBreakStatus.NoBreak;
				}
				else
				{
					brks[posLast] = FLineBreakStatus.AllowBreak;
				}
				break;
			}
		}
	}

	public static uint GetNextChar(string s, ref int index)
	{
		if (index == s.Length)
		{
			return EOS;
		}
		char c = s[index++];
		if (!char.IsHighSurrogate(c))
		{
			return c;
		}
		if (index == s.Length)
		{
			index--;
			return EOS;
		}
		char low = s[index];
		if (!char.IsLowSurrogate(low))
		{
			return c;
		}
		index++;
		return (uint)((((c & 0x3FF) << 10) | (low & 0x3FF)) + 0x10000);
	}

	protected static FLineBreakProperties[] get_lb_prop_lang(string lang)
	{
		FLineBreakProperties[] result;
		if (!lb_prop_lang_map.TryGetValue(lang, out result))
		{
			result = null;
		}
		return result;
	}

	protected static FLineBreakClass get_char_lb_class(uint ch, FLineBreakProperties[] lbpArray, int lbpIndex)
	{
		for (int i = lbpIndex; i < lbpArray.Length; i++)
		{
			FLineBreakProperties lbp = lbpArray[i];
			if (lbp.prop == FLineBreakClass.LBP_Undefined || ch < lbp.start)
			{
				break;
			}
			if (ch <= lbp.end)
			{
				return lbp.prop;
			}
		}
		return FLineBreakClass.LBP_XX;
	}

	protected static FLineBreakClass get_char_lb_class_default(uint ch)
	{
		return get_char_lb_class(ch, lb_prop_default, 0);
	}

	protected static FLineBreakClass get_char_lb_class_lang(uint ch, FLineBreakProperties[] lbpLang)
	{
		FLineBreakClass result = FLineBreakClass.LBP_XX;
		if (lbpLang != null)
		{
			result = get_char_lb_class(ch, lbpLang, 0);
		}
		if (result == FLineBreakClass.LBP_XX)
		{
			result = get_char_lb_class_default(ch);
		}
		return result;
	}

	protected static FLineBreakClass resolve_lb_class(FLineBreakClass lbc, string lang)
	{
		switch (lbc)
		{
		case FLineBreakClass.LBP_SA:
		case FLineBreakClass.LBP_SG:
		case FLineBreakClass.LBP_XX:
			return FLineBreakClass.LBP_AL;
		case FLineBreakClass.LBP_AI:
			if (lang != null && (lang == "zh" || lang == "ja" || lang == "ko"))
			{
				return FLineBreakClass.LBP_ID;
			}
			return FLineBreakClass.LBP_AL;
		default:
			return lbc;
		}
	}
