	private static FLineBreakProperties[] Build(uint[] triples)
	{
		FLineBreakProperties[] result = new FLineBreakProperties[triples.Length / 3];
		for (int i = 0; i < result.Length; i++)
		{
			result[i] = new FLineBreakProperties(triples[i * 3], triples[i * 3 + 1], (FLineBreakClass)triples[i * 3 + 2]);
		}
		return result;
	}

	static FLineBreak()
	{
		lb_prop_lang_map = new Dictionary<string, FLineBreakProperties[]>();
		baTable = new BreakAction[27, 27];
		for (int i = 0; i < 27; i++)
		{
			for (int j = 0; j < 27; j++)
			{
				baTable[i, j] = (BreakAction)baTable_data[i * 27 + j];
			}
		}
		lb_prop_default = Build(lb_prop_default_data);
		lb_prop_English = Build(lb_prop_English_data);
		lb_prop_German = Build(lb_prop_German_data);
		lb_prop_Spanish = Build(lb_prop_Spanish_data);
		lb_prop_French = Build(lb_prop_French_data);
		lb_prop_Russian = Build(lb_prop_Russian_data);
		lb_prop_Chinese = Build(lb_prop_Chinese_data);
		// language keys: GetBreaks compares the language against the literals "zh", "ja", "ko" (0x32095d8 / 0x3209ef8 / 0x3209f00), so two-letter codes are right; the others follow the same scheme (the 165 KB static constructor is not decompilable)
		lb_prop_lang_map["en"] = lb_prop_English;
